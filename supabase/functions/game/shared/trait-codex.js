export const TRAIT_MULTIPLIERS=Object.freeze(['dmg','received','heal','cost','delay','xp','gold','risk']);
const MULTIPLIERS=new Set(TRAIT_MULTIPLIERS);
const EFFECT_NAMES={dmg:'dano causado',received:'dano recebido',heal:'cura recebida',cost:'custo de mana do comando',delay:'recuperação ATB do comando',xp:'XP da batalha',gold:'ouro da batalha',risk:'punição de falha do encontro',bonus:'bônus no d20',hp:'PV',mana:'mana',shield:'escudo',poison:'veneno',burn:'queimadura',freeze:'cargas de lentidão',curse:'cargas de maldição',bleed:'sangramento',haste:'ciclos de aceleração',threat:'ameaça'};
function conditionText([field,op,value]){
 if(value===true)return FIELDS[field];
 const display=field==='hpRatio'||field==='manaRatio'?Math.round(value*100)+'%':VALUES[value]??value;
 return `${FIELDS[field]} ${op==='lte'?'≤':op==='gte'?'≥':'='} ${display}`;
}
function effectText([key,value]){
 if(MULTIPLIERS.has(key))return `${value>1?'+':'−'}${Math.round(Math.abs(value-1)*100)}% ${EFFECT_NAMES[key]}`;
 return `${value>0?'+':'−'}${Math.abs(value)} ${EFFECT_NAMES[key]}`;
}
export function matchesTraitRule(rule,ctx){
 const [key,op,value]=rule.when, actual=ctx[key];
 if(actual==null)return false;
 if(op==='eq')return actual===value;
 if(typeof actual!=='number'||!Number.isFinite(actual))return false;
 return op==='gte'?actual>=value:op==='lte'?actual<=value:false;
}
export const INFERNAL_TRAITS=Object.freeze(rows.map((row,index)=>{
 const rule=Object.freeze({event:row.event,when:Object.freeze(row.when),effects:Object.freeze(row.effects)});
 const destination=row.event==='hit'&&Object.keys(row.effects).some(k=>['poison','burn','freeze','curse','bleed'].includes(k))?' Os estados indicados são aplicados ao alvo.':'';
 return Object.freeze({id:`infernal_${row.side>0?'gift':'burden'}_${String(index+1).padStart(3,'0')}`,name:row.name,cost:row.side*(row.event==='start'||row.event==='reward'?3:4),desc:`${EVENT_TEXT[row.event]}, se ${conditionText(row.when)}: ${Object.entries(row.effects).map(effectText).join('; ')}.${destination}`,mods:Object.freeze({}),rules:Object.freeze([rule])});
}));
const BY_ID=new Map(INFERNAL_TRAITS.map(t=>[t.id,t]));
const cache=new WeakMap();
/** Compile only equipped traits. Invalidation follows ids, including in-place array edits. */
function compiled(p){
 const ids=Array.isArray(p.traits)?p.traits:[], signature=ids.join('|');
 const previous=cache.get(p);if(previous?.signature===signature)return previous.events;
 const events=Object.create(null);
 for(const id of new Set(ids))for(const rule of BY_ID.get(id)?.rules??[])(events[rule.event]??=[]).push(rule);
 cache.set(p,{signature,events});return events;
}
/** Returns a fresh sparse object. Missing multiplicative outputs mean 1; missing deltas mean 0. */
export function traitRules(p,event,ctx={}){
 const out={};if(!p||typeof p!=='object')return out;
 for(const rule of compiled(p)[event]??[]){
  if(!matchesTraitRule(rule,ctx))continue;
  for(const [key,value]of Object.entries(rule.effects))out[key]=MULTIPLIERS.has(key)?(out[key]??1)*value:(out[key]??0)+value;
 }
 return out;
}
